import { chromium, expect } from "@playwright/test"
import { mkdir, writeFile } from "node:fs/promises"
import path from "node:path"

// Opt-in, real HTTP backend. No route fulfillment, provider fixture, or mock transport.
// Use a separately provisioned Bamboo data directory: this creates one diagnostic session.
const baseUrl = process.env.LOTUS_I18N_BASE_URL
if (!baseUrl) throw new Error("Set LOTUS_I18N_BASE_URL to an isolated real Bamboo server serving this dist.")
const output = path.resolve(process.env.LOTUS_I18N_EVIDENCE_DIR || "test-results-real-bamboo/i18n")
await mkdir(output, { recursive: true })
const browser = await chromium.launch({ headless: true })
const evidence = { baseUrl, backend: "real HTTP", provider: "unavailable localhost upstream; no live-model execution claimed", screenshots: [], paths: [], pageErrors: [] }
try {
  const context = await browser.newContext({ locale: "en-US", colorScheme: "dark", viewport: { width: 1440, height: 900 } })
  const page = await context.newPage()
  page.on("pageerror", (error) => evidence.pageErrors.push(error.message))
  const writes = []
  page.on("request", (request) => { if (request.method() === "POST" && /\/chat$/.test(request.url())) writes.push(request.url()) })
  await page.addInitScript(() => localStorage.setItem("bodhi_onboarded_v1", "1"))
  const capture = async (name) => { await page.screenshot({ path: path.join(output, `${name}.png`), animations: "disabled" }); evidence.screenshots.push(`${name}.png`) }
  const openSettings = async (english) => {
    const button = page.getByRole("button", { name: english ? "System Settings" : "系统设置", exact: true })
    const bounds = await button.boundingBox()
    if (!bounds || bounds.x < 0) await page.getByRole("button", { name: english ? "Menu" : "菜单", exact: true }).click()
    await button.click()
    await page.getByRole("button", { name: english ? "General" : "通用", exact: true }).click()
  }
  const assertWidth = async () => expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1)).toBe(true)
  await page.goto(baseUrl)
  const input = page.getByRole("textbox", { name: "Messages", exact: true })
  await expect(input).toBeVisible()
  await expect(page.getByRole("button", { name: "About Ultra orchestration" })).toBeVisible()
  await capture("english-desktop")
  await input.fill("输入法测试 / code <h1>Hello</h1>")
  await input.dispatchEvent("compositionstart", { data: "中" })
  await input.dispatchEvent("keydown", { key: "Enter", keyCode: 229, isComposing: true, bubbles: true })
  await expect(input).toHaveValue("输入法测试 / code <h1>Hello</h1>")
  expect(writes).toHaveLength(0)
  await input.dispatchEvent("compositionend", { data: "中" })
  await input.evaluate((element) => { globalThis.__i18nOriginalComposer = element })
  await openSettings(true)
  await page.locator("#app-language").selectOption("zh-CN")
  await expect(page.locator("html")).toHaveAttribute("lang", "zh-CN")
  await page.getByRole("button", { name: "关闭设置", exact: true }).click()
  const chineseInput = page.getByRole("textbox", { name: "消息", exact: true })
  await expect(chineseInput).toHaveValue("输入法测试 / code <h1>Hello</h1>")
  expect(await chineseInput.evaluate((element) => element === globalThis.__i18nOriginalComposer)).toBe(true)
  await capture("chinese-desktop")
  await page.reload()
  await expect(page.getByRole("textbox", { name: "消息", exact: true })).toBeVisible()
  expect(await page.evaluate(() => localStorage.getItem("lotus_ui_locale_v1"))).toBe("zh-CN")
  evidence.paths.push("English → Chinese, same textarea identity and IME draft; refresh keeps Chinese")
  await openSettings(false)
  await page.locator("#app-language").selectOption("en-US")
  await page.getByRole("button", { name: "Advanced", exact: true }).click()
  await page.getByRole("button", { name: "Provider", exact: true }).click()
  await expect(page.getByText("Default model preferences", { exact: true })).toBeVisible()
  await capture("english-provider-desktop")
  await page.setViewportSize({ width: 390, height: 844 })
  await page.getByRole("button", { name: "Close settings", exact: true }).click()
  await openSettings(true)
  await page.getByRole("button", { name: "Provider", exact: true }).click()
  await assertWidth()
  await capture("english-provider-phone")
  await page.getByRole("button", { name: "System", exact: true }).click()
  await page.getByRole("button", { name: "Clear local storage", exact: true }).click()
  await expect(page.getByRole("heading", { name: "Clear local storage?", exact: true })).toBeVisible()
  await assertWidth()
  await capture("english-confirm-phone")
  await page.getByRole("button", { name: "Cancel", exact: true }).last().click()
  await page.getByRole("button", { name: "Close settings", exact: true }).click()
  await assertWidth()
  await capture("english-composer-phone")
  await openSettings(true)
  await page.locator("#app-language").selectOption("zh-CN")
  await page.getByRole("button", { name: "关闭设置", exact: true }).click()
  await assertWidth()
  await capture("chinese-composer-phone")
  await openSettings(false)
  await page.locator("#app-language").selectOption("en-US")
  await page.getByRole("button", { name: "Close settings", exact: true }).click()
  await page.reload()
  await expect(page.getByRole("textbox", { name: "Messages", exact: true })).toBeVisible()
  expect(await page.evaluate(() => localStorage.getItem("lotus_ui_locale_v1"))).toBe("en-US")
  evidence.paths.push("English provider settings, phone wrapping, cancelable confirmation; Chinese and English phone composer; English refresh persistence")
  // Send only to the deliberately unavailable local upstream in this isolated backend.
  await page.getByRole("textbox", { name: "Messages", exact: true }).fill("i18n diagnostic acceptance: preserve raw backend details")
  await page.getByRole("button", { name: "Send message", exact: true }).click()
  await expect(page.getByText("Message sent, but generation was interrupted", { exact: true })).toBeVisible({ timeout: 45_000 })
  await page.locator("details").filter({ hasText: "Technical details" }).locator("summary").click()
  const diagnostic = await page.locator("details").filter({ hasText: "Technical details" }).innerText()
  expect(diagnostic.length).toBeGreaterThan("Technical details".length)
  await capture("english-real-error-phone")
  evidence.paths.push("Real backend generation failure: English wrapper and unmodified technical diagnostic")
  expect(evidence.pageErrors).toEqual([])
  await writeFile(path.join(output, "evidence.json"), JSON.stringify(evidence, null, 2) + "\n")
  console.log(JSON.stringify(evidence, null, 2))
  await context.close()
} finally { await browser.close() }
